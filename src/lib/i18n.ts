const ATTRIBUTES = ["title", "aria-label", "placeholder", "alt"];

function translate(value: string): string {
  const trimmed = value.trim();
  const normalized = trimmed.replace(/\s+/g, " ");
  const exact = ZH[trimmed] ?? ZH[normalized];
  if (exact) return value.replace(trimmed, exact);
  const moveTo = normalized.match(/^Move to \"(.+)\"$/);
  if (moveTo) return value.replace(trimmed, `移动到“${moveTo[1]}”`);
  if (normalized === "Folder Sync — keep folders mirrored to your servers") {
    return value.replace(trimmed, "文件夹同步 — 保持文件夹与服务器镜像同步");
  }
  const syncStatus = normalized.match(
    /^Folder Sync — (\d+) running(?:, (\d+) syncing)? of (\d+)$/
  );
  if (syncStatus) {
    const [, running, syncing, total] = syncStatus;
    const status = syncing ? `，${syncing} 个同步中` : "";
    return value.replace(
      trimmed,
      `文件夹同步 — ${running} 个运行中${status}，共 ${total} 个`
    );
  }
  const bridgeStatus = normalized.match(
    /^Agent Bridge( \(running\))? — let a local AI agent run commands on your servers$/
  );
  if (bridgeStatus) {
    return value.replace(
      trimmed,
      `智能代理桥接${bridgeStatus[1] ? "（运行中）" : ""} — 让本地 AI 代理在服务器上运行命令`
    );
  }
  if (normalized === "Agent console — live view of what the agent is doing over the bridge") {
    return value.replace(trimmed, "代理控制台 — 实时查看代理通过桥接执行的操作");
  }
  if (normalized === "Split view — show local files next to the server") {
    return value.replace(trimmed, "分栏视图 — 在服务器旁显示本地文件");
  }
  if (normalized === "Terminal is only available for SFTP sessions") {
    return value.replace(trimmed, "终端仅适用于 SFTP 会话");
  }
  const missingProgram = normalized.match(/^couldn't run ([^:]+): program not found$/i);
  if (missingProgram) {
    return value.replace(trimmed, `无法运行 ${missingProgram[1]}：找不到程序`);
  }
  if (/^program not found$/i.test(normalized)) {
    return value.replace(trimmed, "找不到程序");
  }
  const connectTarget = normalized.match(/^Couldn't connect to (.+)$/i);
  if (connectTarget) {
    return value.replace(trimmed, `无法连接到 ${connectTarget[1]}`);
  }
  const authorization = normalized.match(/^(.+) authorization failed$/i);
  if (authorization) {
    return value.replace(trimmed, `${authorization[1]} 授权失败`);
  }
  const pathStatus = normalized.match(/^Couldn't read PATH status: (.+)$/i);
  if (pathStatus) {
    return value.replace(trimmed, `无法读取 PATH 状态：${pathStatus[1]}`);
  }
  const cliCheck = normalized.match(/^CLI check failed: (.+)$/i);
  if (cliCheck) {
    return value.replace(trimmed, `CLI 检查失败：${cliCheck[1]}`);
  }
  const cliUpdate = normalized.match(/^faro-cli update failed: (.+)$/i);
  if (cliUpdate) {
    return value.replace(trimmed, `faro-cli 更新失败：${cliUpdate[1]}`);
  }
  const pathFailure = normalized.match(/^(Add to PATH|Remove from PATH) failed: (.+)$/i);
  if (pathFailure) {
    const action = pathFailure[1].toLowerCase().startsWith("add")
      ? "加入 PATH"
      : "从 PATH 移除";
    return value.replace(trimmed, `${action}失败：${pathFailure[2]}`);
  }
  return value
    .replace(/^Faro (.+) is available\.$/i, "Faro $1 可用。")
    .replace(/^Downloading update(.*)$/i, "正在下载更新$1")
    .replace(/^(\d+) files?$/i, "$1 个文件")
    .replace(/^(\d+) folders?$/i, "$1 个文件夹")
    .replace(/^(.+) saved$/i, "$1 已保存")
    .replace(/^(.+) ago$/i, "$1 前");
}

function visit(root: Node): void {
  if (root.nodeType === Node.TEXT_NODE) {
    const text = root.nodeValue;
    if (text && text.trim() && !root.parentElement?.closest("code, pre")) {
      const next = translate(text);
      if (next !== text) root.nodeValue = next;
    }
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  const element = root as Element;
  if (["SCRIPT", "STYLE", "CODE", "PRE"].includes(element.tagName)) return;
  for (const attr of ATTRIBUTES) {
    const value = element.getAttribute(attr);
    if (!value) continue;
    const next = translate(value);
    if (next !== value) element.setAttribute(attr, next);
  }
  for (const child of Array.from(element.childNodes)) visit(child);
}

/** Start the Chinese renderer. Idempotent so pop-out windows can call it too. */
export function startChineseTranslation(): void {
  if (document.documentElement.dataset.faroLocale === "zh-CN") return;
  document.documentElement.lang = "zh-CN";
  document.documentElement.dataset.faroLocale = "zh-CN";
  visit(document.body);
  const observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") visit(record.target);
      else for (const node of Array.from(record.addedNodes)) visit(node);
      if (record.type === "attributes") visit(record.target);
    }
  });
  observer.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ATTRIBUTES,
  });
}
